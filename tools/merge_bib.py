#!/usr/bin/env python3
"""merge_bib.py - concatenate .bib files, dropping exact-duplicate keys.

Phase-1 bibliography merge: the three papers share ~200 identical citation keys
(DEAC and DRED basebibfile.bib are near-identical), which would crash bibtex with
"repeated entry". This produces a single combined database keeping the FIRST
occurrence of each key (case-insensitive, as bibtex keys are). Sources are listed
thesis-first so hand-curated thesis entries win over paper copies.

This is the minimal merge that lets the integrated thesis compile. The full
semantic dedup (same entry under different keys, conflicting venues) is Phase 2.

Usage: merge_bib.py -o OUT.bib IN1.bib IN2.bib ...
"""
import argparse
import re
import sys

ENTRY_START = re.compile(r"@(\w+)\s*[{(]\s*([^,\s]+)\s*,", re.IGNORECASE)


def iter_entries(text):
    """Yield (key_or_None, raw_text) chunks covering the whole file in order."""
    i, n = 0, len(text)
    while i < n:
        at = text.find("@", i)
        if at == -1:
            if text[i:].strip():
                yield (None, text[i:])
            return
        # preamble/gap before this entry
        if at > i and text[i:at].strip():
            yield (None, text[i:at])
        m = ENTRY_START.match(text, at)
        if not m:
            # stray '@' not starting an entry; emit one char and continue
            yield (None, text[at:at + 1])
            i = at + 1
            continue
        key = m.group(2)
        # brace-match from the opening delimiter
        open_pos = text.index("{" if "{" in text[at:m.end()] else "(", at)
        opener = text[open_pos]
        closer = "}" if opener == "{" else ")"
        depth, j = 0, open_pos
        while j < n:
            c = text[j]
            if c == opener:
                depth += 1
            elif c == closer:
                depth -= 1
                if depth == 0:
                    j += 1
                    break
            j += 1
        yield (key, text[at:j])
        i = j


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("inputs", nargs="+")
    args = ap.parse_args()

    seen = {}
    order = []
    dupes = []
    for path in args.inputs:
        with open(path, encoding="utf-8", errors="replace") as f:
            text = f.read()
        for key, raw in iter_entries(text):
            if key is None:
                continue
            lk = key.lower()
            if lk in seen:
                dupes.append((key, path, seen[lk]))
                continue
            seen[lk] = path
            order.append(raw.strip())

    with open(args.out, "w", encoding="utf-8") as f:
        f.write("%% AUTO-GENERATED by tools/merge_bib.py -- do not edit by hand.\n")
        f.write("%% Phase-1 combined bibliography: union of the thesis + three paper\n")
        f.write("%% .bib files, exact-duplicate keys removed (first occurrence kept).\n")
        f.write("%% Sources (in priority order): " + ", ".join(args.inputs) + "\n\n")
        f.write("\n\n".join(order) + "\n")

    print(f"wrote {args.out}: {len(order)} unique entries, "
          f"{len(dupes)} duplicate keys dropped", file=sys.stderr)


if __name__ == "__main__":
    main()
